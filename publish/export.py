"""Export the public copy of the project (T66).

The file set is the tracked files at HEAD of the source repository (`git ls-tree`), minus the bans of
`config/public.yaml`, minus the `docs/` entries it does not list. The copy is a new git
repository with one commit, branch `main` and no remote. Nothing here pushes, adds a remote or
changes the source repository: it only reads it (`git ls-files`, `git config`).
"""

from __future__ import annotations

import argparse
import fnmatch
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
MESSAGE = "say-it-twice: public copy"


class ExportError(Exception):
    pass


_REPO_VARS = (
    "GIT_INDEX_FILE", "GIT_DIR", "GIT_WORK_TREE", "GIT_COMMON_DIR", "GIT_PREFIX",
    "GIT_OBJECT_DIRECTORY", "GIT_ALTERNATE_OBJECT_DIRECTORIES",
    "GIT_AUTHOR_NAME", "GIT_AUTHOR_EMAIL", "GIT_AUTHOR_DATE",
    "GIT_COMMITTER_NAME", "GIT_COMMITTER_EMAIL", "GIT_COMMITTER_DATE",
)  # fmt: skip


def git_env() -> dict[str, str]:
    """The environment without the variables a git hook or commit sets: a git command here must act on
    the repository its -C names, never on the one that is committing."""
    return {k: v for k, v in os.environ.items() if k not in _REPO_VARS}


def _git(root: Path, *args: str) -> str:
    out = subprocess.run(
        ["git", "-C", str(root), *args],
        check=False,
        capture_output=True,
        text=True,
        env=git_env(),
    )
    if out.returncode != 0:
        raise ExportError(f"git {args[0]} failed in {root}: {out.stderr.strip()}")
    return out.stdout


def load_config(root: Path) -> dict:
    cfg = yaml.safe_load((root / "config" / "public.yaml").read_text(encoding="utf-8"))
    for key in ("ban", "docs", "rewrite", "skip_tests", "scan"):
        if key not in cfg:
            raise ExportError(f"config/public.yaml has no key {key!r}")
    return cfg


def _banned(path: str, ban: list[str]) -> bool:
    """A path equal to an entry (fnmatch) or under it; `[x]` keeps a name out of the copy's text."""
    return any(
        fnmatch.fnmatchcase(path, b.rstrip("/"))
        or fnmatch.fnmatchcase(path, b.rstrip("/") + "/*")
        for b in ban
    )


def file_set(root: Path, cfg: dict) -> list[str]:
    """Tracked files at HEAD that the copy carries."""
    # ls-tree of HEAD, not ls-files: the index may be a hook's temporary one.
    tracked = _git(root, "ls-tree", "-r", "-z", "--name-only", "HEAD").split("\0")
    keep = []
    for path in tracked:
        if not path or _banned(path, cfg["ban"]):
            continue
        if path.startswith("docs/") and not any(
            fnmatch.fnmatchcase(path, pat) for pat in cfg["docs"]
        ):
            continue
        full = root / path
        if not full.is_file() or full.is_symlink():
            continue
        keep.append(path)
    return keep


def _rewrite(path: str, data: bytes, rules: list[dict]) -> bytes:
    for rule in rules:
        if not any(fnmatch.fnmatchcase(path, g) for g in rule["files"]):
            continue
        try:
            text = data.decode("utf-8")
        except UnicodeDecodeError:
            continue
        data = re.sub(rule["pattern"], rule["replace"], text).encode("utf-8")
    return data


def _is_binary(data: bytes) -> bool:
    return b"\0" in data[:8192]


def scan(dest: Path, cfg: dict) -> list[tuple[str, str]]:
    """(path, pattern) for each hit; the matching text is never returned."""
    rules = []
    for entry in cfg["scan"]:
        if isinstance(entry, str):
            entry = {"pattern": entry}
        rules.append(
            (entry["pattern"], re.compile(entry["pattern"]), entry.get("except", []))
        )
    hits = []
    for p in sorted(dest.rglob("*")):
        rel = p.relative_to(dest)
        if not p.is_file() or rel.parts[0] == ".git":
            continue
        data = p.read_bytes()
        if _is_binary(data):
            continue
        text = data.decode("utf-8", errors="replace")
        for pattern, rx, skip in rules:
            if any(fnmatch.fnmatchcase(rel.as_posix(), g) for g in skip):
                continue
            if rx.search(text):
                hits.append((rel.as_posix(), pattern))
    return hits


def _conftest(skips: list[dict]) -> str:
    lines = [
        '"""Generated by `make publish`: tests that need what the public copy leaves out."""',
        "",
        "import pytest",
        "",
        "SKIPS = {",
    ]
    for s in skips:
        lines.append(f"    {s['test']!r}: {s['reason']!r},")
    lines += [
        "}",
        "",
        "",
        "def pytest_collection_modifyitems(items):",
        "    for item in items:",
        "        reason = SKIPS.get(item.nodeid)",
        "        if reason:",
        "            item.add_marker(pytest.mark.skip(reason=reason))",
        "",
    ]
    return "\n".join(lines)


def check_dest(dest: Path, root: Path) -> None:
    if dest == root or root in dest.parents or dest in root.parents:
        raise ExportError(f"{dest} is inside or around the source repository")
    if dest.exists() and (not dest.is_dir() or any(dest.iterdir())):
        raise ExportError(f"{dest} is not an empty directory")


def export(dest: Path, root: Path = ROOT) -> int:
    """Write the copy into `dest`; return the number of files copied."""
    root = root.resolve()
    dest = dest.resolve()
    check_dest(dest, root)
    cfg = load_config(root)
    files = file_set(root, cfg)
    # author_name, when set, names the author and the committer; the email is the source's.
    name = cfg.get("author_name") or _git(root, "config", "user.name").strip()
    email = _git(root, "config", "user.email").strip()
    dest.mkdir(parents=True, exist_ok=True)
    for path in files:
        target = dest / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(_rewrite(path, (root / path).read_bytes(), cfg["rewrite"]))
        shutil.copymode(root / path, target)
    if cfg["skip_tests"]:
        (dest / "conftest.py").write_text(
            _conftest(cfg["skip_tests"]), encoding="utf-8"
        )
    hits = scan(dest, cfg)
    if hits:
        for rel, pattern in hits:
            print(f"secret scan: {rel} matches {pattern}", file=sys.stderr)
        for child in dest.iterdir():
            if child.is_dir() and not child.is_symlink():
                shutil.rmtree(child)
            else:
                child.unlink()
        raise ExportError(
            f"the scan found {len(hits)} hit(s); the copy was removed from {dest}"
        )
    for cmd in (
        ["init", "-q", "-b", "main"],
        ["add", "-A"],
        [
            "-c",
            f"user.name={name}",
            "-c",
            f"user.email={email}",
            "commit",
            "-q",
            "-m",
            MESSAGE,
        ],
    ):
        out = subprocess.run(
            ["git", "-C", str(dest), *cmd],
            check=False,
            capture_output=True,
            text=True,
            env=git_env(),
        )
        if out.returncode != 0:
            raise ExportError(
                f"git {cmd[-1 if cmd[0] == '-c' else 0]} failed: {out.stderr.strip()}"
            )
    return len(files)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="publish", description=__doc__)
    ap.add_argument(
        "--dest", required=True, type=Path, help="empty directory outside the repo"
    )
    ap.add_argument(
        "--root", type=Path, default=ROOT, help="source repository (default: this one)"
    )
    args = ap.parse_args(argv)
    try:
        n = export(args.dest, args.root)
    except ExportError as e:
        print(f"publish: {e}", file=sys.stderr)
        return 1
    print(f"publish: {n} files and one commit in {args.dest.resolve()}")
    return 0
